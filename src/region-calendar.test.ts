import assert from "node:assert/strict";
import { demoData } from "./demo-data.ts";
import { buildSnapshot, readSnapshot, upgradeWorkspace } from "./local-store.ts";
import { calendarBookings, todaySchedule, widgetSnapshot } from "./domain.ts";
import { addDays, dayKey, localInput, setTimeZone, toInstant, validDay } from "./region.ts";
import { calendarEvent, calendarFile } from "./calendar-export.ts";

const old = structuredClone(demoData);
old.bookings[0].price = 10.5;
const migrated = readSnapshot({ version: 1, workspace: old })!;
assert.equal(migrated.bookings[0].price, 10.5);
assert.deepEqual(migrated.bookings, old.bookings);
assert.ok(!('payments' in migrated));
assert.ok(!('defaultCurrency' in migrated));
const data = upgradeWorkspace(structuredClone(demoData));
data.timeZone = "Asia/Jakarta";
const booking = { ...data.bookings[0], rentalStatus: "reserved" as const, approvalStatus: "approved" as const, startAt: "2026-09-30T18:00:00Z", endAt: "2026-10-02T01:00:00Z" };
data.bookings = [booking];
assert.deepEqual(readSnapshot(JSON.parse(JSON.stringify(buildSnapshot(data)))), JSON.parse(JSON.stringify(data)));
const invalid = buildSnapshot(data); invalid.workspace.timeZone = 'Bad/Zone';
assert.equal(readSnapshot(invalid), null);
assert.throws(() => calendarEvent({ ...booking, rentalStatus: 'cancelled' }, 'Item'), /errors.calendarEvent/);
assert.throws(() => calendarEvent({ ...booking, approvalStatus: 'rejected' }, 'Item'), /errors.calendarEvent/);
assert.equal(validDay("2024-02-29"), true); assert.equal(validDay("2026-02-29"), false);
assert.equal(addDays("2026-12-31", 1), "2027-01-01");
assert.equal(toInstant("2026-10-01T01:00", "Asia/Jakarta"), booking.startAt.replace("00Z", "00.000Z"));
assert.equal(localInput(booking.startAt, "Asia/Jakarta"), "2026-10-01T01:00");
assert.equal(dayKey(booking.startAt, "America/New_York"), "2026-09-30");
assert.throws(() => toInstant("2026-03-08T02:30", "America/New_York"), /errors.localTime/);
assert.throws(() => toInstant("2026-11-01T01:30", "America/New_York"), /errors.ambiguousTime/);
assert.throws(() => toInstant("2026-10-01T24:00", "Asia/Jakarta"), /errors.localTime/);
setTimeZone("Asia/Jakarta");
const now = new Date("2026-09-30T18:30:00Z");
assert.equal(todaySchedule([booking], now).length, 1);
assert.equal(calendarBookings([booking], "2026-09-30", now).length, 0);
assert.equal(calendarBookings([booking], "2026-10-01", now).length, 1);
assert.equal(widgetSnapshot({ ...data, bookings: [booking] }, now).day, "2026-10-01");
assert.equal(widgetSnapshot(data, now).timeZone, "Asia/Jakarta");
const event = calendarEvent(booking, "A, B;\n" + "장비".repeat(40));
assert.deepEqual(Object.keys(event).sort(), ["end", "start", "title"]);
const ics = calendarFile({ ...booking, customerPhone: "PRIVATE_PHONE", memo: "PRIVATE_NOTE", customerName: "PRIVATE_NAME" }, "A, B;\n" + "장비".repeat(40), +now);
assert.ok(!ics.includes("PRIVATE"));
assert.ok(ics.includes("DTSTART:20260930T180000Z\r\n"));
assert.ok(ics.includes("A\\, B\\;\\n"));
assert.ok(ics.split("\r\n").every(line => new TextEncoder().encode(line).length <= 75));
console.log("Migration, timezone/DST and calendar privacy checks passed");
